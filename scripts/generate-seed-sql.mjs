// Reads supabase/seed/playboy_issue_seed_data.csv and writes
// supabase/seed/seed.sql — a plain SQL file you can paste into the Supabase
// SQL editor (or run via `supabase db execute`) to populate `issues`.
//
// Re-running this is safe: it regenerates seed.sql from the CSV, and the SQL
// itself uses ON CONFLICT (year, issue_period) DO NOTHING, so it won't
// clobber rows you've already corrected in the app.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "csv-parse/sync";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const csvPath = path.join(__dirname, "..", "supabase", "seed", "playboy_issue_seed_data.csv");
const outPath = path.join(__dirname, "..", "supabase", "seed", "seed.sql");

const raw = readFileSync(csvPath, "utf-8");
const rows = parse(raw, { columns: true, skip_empty_lines: true });

function sqlString(value) {
  if (value === undefined || value === null || value.trim() === "") return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}

const validConfidence = new Set(["verified", "wikipedia-sourced", "needs-verification", "unknown"]);

const values = rows.map((row) => {
  const year = parseInt(row.year, 10);
  if (Number.isNaN(year)) throw new Error(`Bad year in row: ${JSON.stringify(row)}`);
  const confidence = validConfidence.has(row.source_confidence) ? row.source_confidence : "unknown";
  return `  (${year}, ${sqlString(row.issue_period)}, ${sqlString(row.display_label)}, ${sqlString(
    row.cover_model
  )}, ${sqlString(row.playmate_name)}, ${sqlString(row.interview_subject)}, ${sqlString(row.notable_cover_names)}, ${sqlString(confidence)})`;
});

const sql = `-- Generated by scripts/generate-seed-sql.mjs from playboy_issue_seed_data.csv
-- Do not hand-edit; edit the CSV and regenerate instead.
insert into public.issues
  (year, issue_period, display_label, cover_model, playmate_name, interview_subject, notable_cover_names, source_confidence)
values
${values.join(",\n")}
on conflict (year, issue_period) do nothing;
`;

writeFileSync(outPath, sql, "utf-8");
console.log(`Wrote ${rows.length} issues to ${path.relative(process.cwd(), outPath)}`);
